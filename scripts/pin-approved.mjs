import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { PinataStorage } from "../storage/pinata.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const reviewPath = path.join(root, "reviews", "review-status.json");
if (!fs.existsSync(reviewPath)) throw new Error("Create reviews/review-status.json with explicit rights_confirmed and owner_approved flags first.");
const reviews = JSON.parse(fs.readFileSync(reviewPath, "utf8"));
const key = process.argv[2];
if (!key || !reviews[key]) throw new Error("Usage: npm run pin:approved -- \"Artwork title\"");
const review = reviews[key];
if (review.rights_confirmed !== true || review.owner_approved !== true) throw new Error("Public IPFS upload blocked: rights_confirmed and owner_approved must both be true.");
if (review.public_ipfs_uploaded === true) throw new Error("This artwork is already marked as uploaded. Check its CID before retrying.");
const collectionPath = path.join(root, "collection.json");
if (!fs.existsSync(collectionPath)) throw new Error("collection.json is required.");
const collection = JSON.parse(fs.readFileSync(collectionPath, "utf8"));
const item = collection.items.find((entry) => entry.name === key);
if (!item?.image) throw new Error("Artwork title not found in collection.json.");
const filePath = path.resolve(root, "assets", item.image);
if (!filePath.startsWith(path.join(root, "assets") + path.sep) || !fs.existsSync(filePath)) throw new Error("Artwork file is missing or outside assets/.");
const storage = new PinataStorage();
const result = await storage.uploadFile(filePath);
review.public_ipfs_uploaded = true;
review.image_cid = result.cid;
review.image_uri = result.uri;
review.uploaded_at = new Date().toISOString();
fs.writeFileSync(reviewPath, JSON.stringify(reviews, null, 2) + "\n");
console.log(JSON.stringify({ title: key, ...result }, null, 2));
